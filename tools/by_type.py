"""Index of the incidents by type of control failure, computed from data/incidents.json.

Used by tools/export_dataset.py, which writes docs/by-type.md and the block between the by-type markers of
README.md, and checks both with --check. Nothing here is typed by hand: every count and every date is read
from the data. The type is this project's own tag (see docs/limits.md), not a label from the protocols.
"""
import re

START = "[//]: # (by-type:start generated by tools/export_dataset.py, do not edit by hand)"
END = "[//]: # (by-type:end)"
REPO = "https://github.com/RealSpap/onchain-postmortems"

# The question each tag stands for. A tag with no entry here still gets listed, with a neutral line.
QUESTION = {
    "Access-Control": "Who was allowed to call it?",
    "Rounding/Math-Bug": "Did the arithmetic hold at the edges?",
    "Bridge": "Who checked the message that moved the funds?",
    "Oracle": "Where did the price come from, and who could move it?",
    "Key-Compromise": "Who held the key, and how was it used?",
    "Donation-Attack": "What happens to the accounting when someone sends tokens in?",
    "Governance": "Who could change the rules, and how fast?",
}


def groups(rows):
    by = {}
    for r in rows:
        by.setdefault(r["category"], []).append(r)
    return sorted(by.items(), key=lambda kv: (-len(kv[1]), kv[0]))


def span(rows):
    dates = sorted(r["date"][:10] for r in rows)
    return dates[0], dates[-1]


def anchor(cat):
    return re.sub(r"[^a-z0-9-]", "", cat.lower().replace("/", "-").replace(" ", "-"))


def money(n):
    return f"${n:,}"


def render_block(rows):
    first, last = span(rows)
    lines = [
        START,
        f"{len(rows)} incidents, from {first} to {last} (the latest incident in the data). Counts and totals are read from `data/incidents.json`.",
        "",
        "| Type of control failure | Incidents | Loss ($) | The question |",
        "|---|---|---|---|",
    ]
    for cat, rs in groups(rows):
        lines.append(f"| [{cat}](docs/by-type.md#{anchor(cat)}) | {len(rs)} | {money(sum(r['loss_usd'] for r in rs))} | {QUESTION.get(cat, 'See the incidents.')} |")
    lines += ["", "Find the incidents that look like your protocol: [docs/by-type.md](docs/by-type.md), or `python3 tools/find_incidents.py --category Bridge --chain Ethereum`.", "", END]
    return "\n".join(lines)


def render_page(rows):
    first, last = span(rows)
    out = [
        "# Incidents by type of control failure",
        "",
        "Back to the [README](../README.md).",
        "",
        f"Generated by `tools/export_dataset.py` from `data/incidents.json`: {len(rows)} incidents, from {first} to {last} (the latest incident in the data). "
        "Nothing on this page is typed by hand. The type is this project's own tag, chosen to make the list easy to scan; it is not a label from the protocols, the press or DefiLlama, "
        "and several incidents could carry more than one (see [limits](limits.md)). The loss figures follow the marks of the [Index](../INDEX.md): "
        "**≥** known floor, **≈** recomputed, **†** sourced, not recomputed.",
        "",
        "To find the incidents that look like your protocol: pick the question closest to how it works, read the incidents under it, then open the ones on your chain. "
        "From the command line: `python3 tools/find_incidents.py --category Oracle --chain Ethereum --text vault`.",
        "",
        "| Type | Incidents | Loss ($) |",
        "|---|---|---|",
    ]
    for cat, rs in groups(rows):
        out.append(f"| [{cat}](#{anchor(cat)}) | {len(rs)} | {money(sum(r['loss_usd'] for r in rs))} |")
    for cat, rs in groups(rows):
        out += ["", f"## {cat}", "", f"*{QUESTION.get(cat, 'See the incidents.')}* {len(rs)} incidents, {money(sum(r['loss_usd'] for r in rs))} in total.", "",
                "| Date | Protocol | Loss ($) | Chain | Mechanism | Folder |", "|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: r["date"], reverse=True):
            mark = ("≥ " if r["floor"] else "") + ("≈ " if r["approximate"] else "") + ("† " if r["sourced"] else "")
            out.append(f"| {r['date']} | {r['protocol']} | {mark}{r['loss_usd']:,} | {r['chain']} | {r['mechanism']} | [{r['slug']}](../incidents/{r['slug']}/) |")
    return "\n".join(out) + "\n"


def splice(readme_text, block):
    """Replace the generated block in the README text, or fail loudly when the markers are missing."""
    a, b = readme_text.find(START), readme_text.find(END)
    if a < 0 or b < a:
        raise SystemExit("README.md: the by-type markers were not found")
    return readme_text[:a] + block + readme_text[b + len(END):]
